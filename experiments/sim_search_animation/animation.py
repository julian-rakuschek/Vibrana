def main2(values, query):
    d = stumpy.mass(query, values, normalize=True)

    for i in tqdm(range(len(d))):
        plt.clf()
        fig, ax = plt.subplots(nrows=3, ncols=1)
        fig.set_size_inches(30, 11)
        ax[0].plot(values, color="black")
        ax[0].set_xlim([0, len(values)])
        ax[1].plot(np.arange(i, i + len(query)), query, color="indigo")
        ax[1].set_xlim([0, len(values)])
        ax[1].set_ylim([-2, 2])
        ax[0].axvspan(i, i + len(query), color='red', alpha=0.25)
        ax[1].axvspan(i, i + len(query), color='red', alpha=0.25)
        ax[2].plot(d[:i], color="indigo")
        ax[2].set_xlim([0, len(values)])
        plt.savefig(f'search_frames/frame_{str(i).zfill(4)}.png', dpi=100, bbox_inches='tight')
        plt.close(fig)


