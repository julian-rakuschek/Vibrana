def loadEnergyConsumptionData(filename) -> pd.DataFrame:
    df = pd.read_csv(filename)
    timestamps = df["utc_timestamp"]
    df = df.drop(columns=['cet_cest_timestamp', 'utc_timestamp', 'interpolated'])
    df = df.ffill()
    A = df.to_numpy()
    A[np.isnan(A)] = 0
    A_shifted = np.insert(np.delete(A, -1, axis=0), 0, np.zeros((1, A.shape[1])), axis=0)
    original = A - A_shifted
    df = pd.DataFrame(original, columns=df.columns)
    df = pd.concat([timestamps, df], axis=1)
    df["utc_timestamp_date"] = pd.to_datetime(df["utc_timestamp"]).dt.date
    df["utc_timestamp"] = pd.to_datetime(df["utc_timestamp"]).values
    return df


